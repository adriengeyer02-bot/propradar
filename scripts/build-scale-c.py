#!/usr/bin/env python3
"""Build app/data/scale-c.json: the scores computed with scale C (approved by
Geyer on 2026-11-25) for the firms whose contract was read by hand.

  python3 -I scripts/build-scale-c.py audits/score-proposal-c-2026-11-25.json

Applied firms (SCORING.md, section "Scale C"):
- contract read in full: the scale C score, up or down;
- excerpts re-read by hand: only when the confirmed clauses lower the score
  (by 10 points at most); never a rise before a full reading.
Everything else keeps its current score and pipeline.
"""
import json, re, sys

PROPOSAL = json.load(open(sys.argv[1]))
SOURCES = json.load(open('audits/terms-archive/sources.json'))
OUT = 'app/data/scale-c.json'


def public_url(slug, source):
    if source.startswith('https://'):
        return source
    urls = SOURCES.get(slug, {}).get('urls', [])
    terms = [u for u in urls if re.search(r'terms|conditions|legal|tos', u, re.I)]
    return (terms or urls or [''])[0]


def tier(row):
    why = row['ceilingWhy']
    if 'inconnue' in why: return 'unknown'
    if why.startswith('< 1'): return 'lt1'
    if why.startswith('1-2'): return 'y1to2'
    if 'très large' in why: return 'y8veryLarge'
    if 'preuve' in why and 'pas de preuve' not in why:
        return 'y5evidence' if row['ceiling'] == 95 else 'y3evidence'
    return 'y2plus'


firms = {}
for r in PROPOSAL['rows']:
    full = r['confidence'] == 'contrat lu en entier'
    excerpt = r['confidence'] == 'extraits relus à la main' and r['delta'] < 0
    if not (full or excerpt):
        continue
    items = []
    for it in r['items']:
        src = public_url(r['slug'], it['source']) if it['source'] else ''
        if it['code'] not in ('TPW', 'TPMID') and not src.startswith('https://'):
            sys.exit(f"{r['slug']} {it['code']}: no public https source")
        text = it['text']
        if len(text) > 480:
            text = text[:477].rsplit(' ', 1)[0] + '…'
        items.append({'code': it['code'], 'points': it['points'], 'text': text, 'source': src, 'locator': it['locator']})
    entry = {
        'score': r['proposed'], 'previous': r['current'], 'raw': r['raw'],
        'ceiling': r['ceiling'], 'tier': tier(r), 'founded': r['founded'],
        'ceilingEvidence': r['ceilingEvidence'], 'penalties': items,
        'reading': 'full' if full else 'excerpts', 'checkedOn': '2026-11-25',
    }
    contract = sum(i['points'] for i in items if i['code'] in ('B1', 'B2', 'B2A', 'B3', 'B4', 'B5', 'B6', 'B7'))
    if contract > PROPOSAL['weights']['Bcap']:
        entry['contractCap'] = PROPOSAL['weights']['Bcap']
    firms[r['slug']] = entry

json.dump({'version': 'C', 'approvedOn': '2026-11-25', 'approvedBy': 'Geyer',
           'note': 'Generated by scripts/build-scale-c.py from audits/score-proposal-c-2026-11-25.json. Do not edit by hand.',
           'firms': dict(sorted(firms.items()))}, open(OUT, 'w'), ensure_ascii=False, indent=1)
open(OUT, 'a').write('\n')
print(len(firms), 'firms', sorted((s, e['previous'], e['score']) for s, e in firms.items()))
